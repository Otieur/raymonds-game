"""
Writes a trained network as a TypeScript module the client and the scripts can import, and a record
beside it.

    train/.venv/bin/python train/export.py --run <dir> --out assets/models/<name> [--note "..."]

The module holds the layer shapes, the observation and action versions, and the weights as 16-bit
floats in one base64 string. ONNX is not written yet: the onnx package is not installed.
"""
from __future__ import annotations

import argparse
import base64
import datetime
import json
import subprocess
from pathlib import Path

import numpy as np
import torch

from model import ACTIONS, OBS_SIZE, Net

OBS_VERSION = 3
ACTIONS_VERSION = 2


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", required=True)
    parser.add_argument("--out", required=True)
    parser.add_argument("--note", default="")
    args = parser.parse_args()
    net = Net()
    net.load_state_dict(torch.load(Path(args.run) / "weights.pt", map_location="cpu"))
    layers = [net.trunk[0], net.trunk[2], net.trunk[4], net.policy, net.value]
    names = ["trunk0", "trunk1", "trunk2", "policy", "value"]
    shapes = []
    parts = []
    for layer in layers:
        w = layer.weight.detach().numpy().astype(np.float16)
        b = layer.bias.detach().numpy().astype(np.float16)
        shapes.append([int(w.shape[1]), int(w.shape[0])])
        parts.append(w.reshape(-1))
        parts.append(b.reshape(-1))
    blob = np.concatenate(parts).astype("<f2").tobytes()
    data = base64.b64encode(blob).decode("ascii")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    record = {
        "name": out.name,
        "date": datetime.date.today().isoformat(),
        "commit": commit,
        "run": str(args.run),
        "obsVersion": OBS_VERSION,
        "actionsVersion": ACTIONS_VERSION,
        "obs": OBS_SIZE,
        "actions": ACTIONS,
        "layers": dict(zip(names, shapes)),
        "note": args.note,
    }
    out.with_suffix(".json").write_text(json.dumps(record, indent=2) + "\n")
    module = "\n".join(
        [
            "/**",
            f" * Generated by train/export.py on {record['date']} from {args.run}, commit {commit}. Do not edit by hand.",
            " */",
            "import type { ModelWeights } from '../../src/env/mlp.ts';",
            "",
            "export const MODEL: ModelWeights = {",
            f"  name: {json.dumps(out.name)},",
            f"  obsVersion: {OBS_VERSION},",
            f"  actionsVersion: {ACTIONS_VERSION},",
            f"  shapes: {json.dumps(shapes)},",
            f"  data: {json.dumps(data)},",
            "};",
            "",
        ]
    )
    out.with_suffix(".ts").write_text(module)
    print(f"Wrote {out.with_suffix('.ts')} ({len(data) / 1e6:.1f} MB) and its record.")


if __name__ == "__main__":
    main()
